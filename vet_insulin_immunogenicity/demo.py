#!/usr/bin/env python3
"""Demo: run both species workflows and write the head-to-head comparison.

    python demo.py                # cat + dog, illustrative backend
    python demo.py --offline      # refuse to fetch anything not already cached

Writes results/dog/, results/cat/ and results/comparison.md.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from vetimmuno import epitope, workflow
from vetimmuno.insulin import natural_insulin
from vetimmuno.report import _table

ROOT = Path(__file__).resolve().parent


def comparison(results: dict) -> str:
    dog, cat = results["dog"], results["cat"]
    out = ["# Dog vs cat: what actually differs\n",
           "*Generated by `demo.py`. The two workflows are the same code with "
           "different species configs; everything below is a measured difference "
           "between the two species, not a difference in method.*\n"]

    out.append("## The molecule\n")
    out.append("**RIGOROUS** — UniProt reviewed mature chains, positional comparison.\n")
    rows = []
    for species in ("dog", "cat"):
        own = natural_insulin(species)
        for donor in ("human", "bovine", "pig"):
            drug = natural_insulin(donor)
            burden = epitope.foreign_burden(drug, own)
            rows.append([species, f"{donor} insulin", burden["n_differences"],
                         ", ".join(burden["differences"]) or "—",
                         burden["n_neo_cores"]])
    out.append(_table(["recipient", "product", "foreign residues", "positions",
                       "non-self 9-mer cores"], rows))
    out.append("")
    out.append(
        "Two things this table says that a residue count alone does not:\n\n"
        "* **Porcine insulin is the dog's own molecule.** Zero differences, zero "
        "non-self cores — the only species/product pair here with nothing for an "
        "epitope screen to find. The cat has no equivalent; its closest natural "
        "match, bovine insulin, still differs at A18.\n"
        "* **Where a difference sits matters more than how many there are.** The "
        "dog's single difference from human insulin is B30, the last residue of "
        "the B chain, and it generates exactly one non-self register. Bovine "
        "insulin's two differences sit at A8/A10, inside the A chain, and "
        "generate ten. Counting residues would rank these the other way round.\n")

    out.append("## The prediction infrastructure\n")
    out.append("**MEASURED** — panel construction and applicability-domain distances "
               "computed in this run.\n")
    rows = []
    for species, res in (("dog", dog), ("cat", cat)):
        for row in res["domain"]["rows"]:
            rows.append([species, row["locus"], row["training_molecules"],
                         f"{row['train_p5']:.3f}", f"{row['panel_median']:.3f}",
                         f"{row['n_out']}/{row['n_total']}"])
    out.append(_table(["species", "locus", "training molecules",
                       "training 5th pct NN identity", "panel median NN identity",
                       "out-of-domain"], rows))
    out.append("")
    out.append(
        "The asymmetry is structural, not incidental:\n\n"
        "* IPD-MHC maintains a curated canine DLA section under ISAG nomenclature. "
        "It has **no feline section at all**, so the FLA panel in this run had to "
        "be scraped from GenBank/RefSeq: no allele names, no curation, no "
        "denominator.\n"
        "* Neither species has an allele-**frequency** database, so neither panel "
        "can be converted into a population-coverage percentage. The human "
        "convention of quoting \"95–98% population coverage\" has no analogue "
        "here for either animal.\n"
        "* Every feline molecule lands outside NetMHCIIpan-4.3's training space; "
        "the canine panel is mostly outside it but has members close enough to "
        "call marginal. That is the honest ceiling on how much weight a binding "
        "score can carry in each species.\n")

    out.append("## Validation\n")
    rows = []
    for species, res in (("dog", dog), ("cat", cat)):
        vr = res["validation"]
        rows.append([species, f"{vr.passed}/{len(vr.checks)}",
                     ", ".join(c.id for c in vr.failed) or "none",
                     ", ".join(c.id for c in vr.checks if c.status == "SKIP") or "none"])
    out.append(_table(["species", "checks passed", "failed", "skipped"], rows))
    out.append("")
    out.append(
        "`KAT-3` is skipped for the cat and passes for the dog, and that single "
        "difference is the clearest statement of the whole comparison: the dog "
        "has a marketed insulin (porcine) that is sequence-identical to its own, "
        "so the identity control is a real product. No such control exists for "
        "the cat.\n")

    out.append("## Bottom line\n")
    out.append(
        "**Dog** — a species-matched product has no T-cell epitope question to "
        "answer; put the analytical effort into aggregation, process impurities "
        "and PTMs. A human-sequence product raises a single, terminal, "
        "well-bounded register. Analogue chemistry (glargine's B31-B32 extension, "
        "the acyl chains on detemir and degludec) moves more mass than the "
        "species gap does.\n\n"
        "**Cat** — four differences, three of them interior to the A chain, so "
        "the non-self registers are real and clustered at A8/A10/A18. That "
        "cluster is small enough to interrogate properly. But the FLA "
        "infrastructure will not support a quantitative population risk "
        "statement, so the defensible output is a ranked register-level "
        "hypothesis list, reported RUO, ideally read out in a feline PBMC assay "
        "against those specific A-chain peptides rather than argued from scores.\n\n"
        "**Both** — the sequence-level analysis (section 1 of each report) is "
        "model-free and carries the regulatory weight. The binding layer is "
        "extrapolation with no species benchmark, and the workflow says so in "
        "every artefact it writes rather than in a footnote.\n")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--offline", action="store_true")
    parser.add_argument("--backend", choices=("surrogate", "netmhciipan"),
                        default="surrogate")
    args = parser.parse_args()

    results = {}
    for species in ("dog", "cat"):
        print(f"=== {species} ===")
        res = workflow.run(species, backend_name=args.backend, offline=args.offline)
        vr = res["validation"]
        print(f"  {vr.passed}/{len(vr.checks)} checks passed"
              + (f", FAILED: {[c.id for c in vr.failed]}" if vr.failed else ""))
        print(f"  report: {res['outdir'] / 'report.md'}")
        results[species] = res

    path = ROOT / "results" / "comparison.md"
    path.write_text(comparison(results))
    print(f"\ncomparison: {path}")
    return 1 if any(r["validation"].failed for r in results.values()) else 0


if __name__ == "__main__":
    sys.exit(main())
