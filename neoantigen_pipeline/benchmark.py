"""Does the selection layer actually rank real neoantigens above decoys?

A pipeline that produces a confident-looking top-34 list without ever being
scored against ground truth is not evidence of anything. This module builds
the only ground truth that is publicly obtainable without a data-access
agreement, and is explicit about what that truth is and is not.

Positives
    IEDB epitopes with a POSITIVE human T-cell assay, human source antigen,
    MHC class I -- filtered to those that are exactly one substitution away
    from a human reference proteome k-mer and do not themselves occur in the
    proteome. That difference is a somatic-mutation-shaped change, and it
    hands us the wild-type counterpart for free, so agretopicity is
    computable exactly as it is in the main pipeline.

Negatives
    Mutant peptides generated by this pipeline from real TCGA melanoma
    missense mutations in *other* patients, matched to each positive on HLA
    allele and length.

    These are UNLABELLED, not verified non-immunogenic. Some small fraction
    are presumably immunogenic and were never tested. That makes this a
    discrimination/enrichment test with a conservative bias, not a clean ROC.
    Reported AUCs are therefore lower bounds on separability, and are labelled
    as such everywhere they appear.

Leakage
    `tcr_prior` is computed by alignment to IEDB positives, so on this
    benchmark it is circular. The benchmark drops the query peptide and any
    exact duplicate from the reference set and, more importantly, reports the
    composite score BOTH with and without that feature.
"""

from __future__ import annotations

import random
import re
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np
import pandas as pd

from . import features as F
from . import fetch, presentation, selfindex

ALLELE_RE = re.compile(r"^HLA-[ABC]\*\d{2}:\d{2}$")


def find_wt_counterpart(pep: str, index) -> Optional[str]:
    """The self k-mer exactly one substitution away from `pep`, or None.

    Returns None when the peptide itself occurs in the proteome (then it is a
    self peptide, not a neoepitope) and when nothing is one substitution away.
    When several self k-mers qualify the first is kept and the ambiguity is not
    hidden -- `one_mismatch` returns them all if a caller wants to inspect.
    """
    hits = index.one_mismatch(pep)
    return hits[0] if hits else None


def build_positive_set(proteome: Dict[str, str], lengths=(9, 10),
                       indexes: Optional[Dict[int, object]] = None) -> pd.DataFrame:
    """Mine IEDB for validated, mutation-shaped human class-I epitopes."""
    rows = fetch.iedb_human_tumor_epitopes()
    df = pd.DataFrame(rows)
    if df.empty:
        return df
    df = df[df["linear_sequence"].notna()]
    df["length"] = df["linear_sequence"].str.len()
    df = df[df["length"].isin(lengths)]
    df["allele"] = df["mhc_allele_name"].astype(str)
    df = df[df["allele"].str.match(ALLELE_RE, na=False)]
    df = df[df["linear_sequence"].str.match(r"^[ACDEFGHIKLMNPQRSTVWY]+$", na=False)]
    df = df.drop_duplicates(subset=["linear_sequence", "allele"])

    indexes = indexes or selfindex.build_indexes(proteome, sorted(set(df["length"])))
    out = []
    for L in sorted(set(df["length"])):
        sub = df[df["length"] == L]
        idx = indexes[int(L)]
        for _, r in sub.iterrows():
            wt = find_wt_counterpart(r["linear_sequence"], idx)
            if wt is None:
                continue
            out.append({"peptide": r["linear_sequence"], "wt_peptide": wt,
                        "allele": r["allele"], "length": int(L),
                        "antigen": r.get("parent_source_antigen_name"),
                        "disease": (r.get("disease_names") or [None])[0]
                        if isinstance(r.get("disease_names"), list) else r.get("disease_names"),
                        "pubmed_id": r.get("pubmed_id"), "label": 1})
    return pd.DataFrame(out).drop_duplicates(subset=["peptide", "allele"])


def add_ranks(d: pd.DataFrame, batch_size: int = 500,
              verbose: bool = True) -> pd.DataFrame:
    """Attach mutant and wild-type %rank for each row's own allele. Cached,
    so calling it twice on overlapping data costs one network round."""
    d = d.copy()
    frames = []
    for (allele, L), grp in d.groupby(["allele", "length"]):
        peps = list(dict.fromkeys(list(grp["peptide"]) + list(grp["wt_peptide"].dropna())))
        pr = presentation.predict_iedb(peps, [allele], int(L), "I",
                                       batch_size=batch_size, progress=False)
        frames.append(pr)
        if verbose:
            print(f"  ranked {allele} L={L}: {len(grp)} rows", flush=True)
    if not frames:
        d["mut_rank"] = np.nan
        d["wt_rank"] = np.nan
        return d
    P = pd.concat(frames, ignore_index=True)
    rank = dict(zip(zip(P["peptide"], P["allele"]), P["percentile_rank"]))
    d["mut_rank"] = [rank.get((p, a), np.nan) for p, a in zip(d["peptide"], d["allele"])]
    d["wt_rank"] = [rank.get((w, a), np.nan) if isinstance(w, str) else np.nan
                    for w, a in zip(d["wt_peptide"], d["allele"])]
    return d


RANK_STRATA = (0.0, 0.1, 0.5, 2.0, 100.0)


def add_rank_stratum(d: pd.DataFrame, edges: Sequence[float] = RANK_STRATA) -> pd.DataFrame:
    """Bin rows by predicted %rank so a comparison can be made *within* a
    presentation stratum, where the binding predictor has little room left."""
    d = d.copy()
    labels = [f"{edges[i]}-{edges[i+1]}%" for i in range(len(edges) - 1)]
    d["rank_bin"] = pd.cut(d["mut_rank"], bins=list(edges), labels=labels,
                           include_lowest=True)
    return d


def stratified_evaluate(d: pd.DataFrame, score_cols: Sequence[str],
                        min_per_class: int = 8) -> pd.DataFrame:
    """AUC of each score *within* each predicted-binding stratum.

    Strata with fewer than `min_per_class` of either class are reported with
    their counts and a NaN AUC rather than a number nobody should trust.
    """
    d = add_rank_stratum(d)
    rows = []
    for stratum, grp in d.groupby("rank_bin", observed=True):
        n1 = int((grp["label"] == 1).sum())
        n0 = int((grp["label"] == 0).sum())
        row = {"rank_bin": str(stratum), "n_pos": n1, "n_dec": n0}
        enough = n1 >= min_per_class and n0 >= min_per_class
        for c in score_cols:
            row[c] = round(auc(grp["label"], grp[c]), 3) if enough and c in grp else float("nan")
        rows.append(row)
    return pd.DataFrame(rows)


def balance_by_stratum(d: pd.DataFrame, ratio: int = 3, seed: int = 0,
                       edges: Sequence[float] = RANK_STRATA) -> pd.DataFrame:
    """Subsample decoys so each binding stratum holds `ratio` x its positives.

    After this, the two classes have (approximately) the same distribution of
    predicted %rank, so an overall AUC above 0.5 cannot be explained by
    binding strength alone.
    """
    d = add_rank_stratum(d, edges)
    rng = np.random.default_rng(seed)
    keep = []
    for stratum, grp in d.groupby("rank_bin", observed=True):
        pos = grp[grp["label"] == 1]
        dec = grp[grp["label"] == 0]
        if pos.empty:
            continue
        n = min(len(dec), ratio * len(pos))
        keep.append(pos)
        if n:
            keep.append(dec.sample(n=n, random_state=int(rng.integers(0, 2 ** 31))))
    return pd.concat(keep, ignore_index=True) if keep else d.iloc[0:0]


def match_decoys_by_binding(positives: pd.DataFrame, pool: pd.DataFrame,
                            ratio: int = 5, tol_log10: float = 0.3,
                            seed: int = 0) -> pd.DataFrame:
    """Pick decoys whose predicted binding matches each positive's.

    Why this matters more than anything else in this file: IEDB epitopes were
    largely *discovered* because they bind well, so an unmatched decoy set makes
    the benchmark a binder-vs-non-binder test, which NetMHCpan wins by
    construction and which says nothing about immunogenicity. Matching decoys to
    positives on predicted %rank removes that axis and leaves the question the
    selection layer actually exists to answer: among peptides that are all
    presented, which ones does a T cell see?
    """
    rng = np.random.default_rng(seed)
    take = []
    used = set()
    for _, p in positives.iterrows():
        if pd.isna(p.get("mut_rank")):
            continue
        cand = pool[(pool["allele"] == p["allele"]) & (pool["length"] == p["length"])
                    & pool["mut_rank"].notna()]
        if cand.empty:
            continue
        dist = np.abs(np.log10(cand["mut_rank"].clip(lower=1e-3))
                      - np.log10(max(p["mut_rank"], 1e-3)))
        near = cand[dist <= tol_log10]
        if len(near) < ratio:                     # widen to the nearest available
            near = cand.iloc[np.argsort(dist.to_numpy())[:ratio * 3]]
        near = near[~near["peptide"].isin(used)]
        if near.empty:
            continue
        pick = near.sample(n=min(ratio, len(near)),
                           random_state=int(rng.integers(0, 2 ** 31)))
        used.update(pick["peptide"])
        take.append(pick)
    if not take:
        return pd.DataFrame(columns=pool.columns)
    return pd.concat(take, ignore_index=True).drop_duplicates(subset=["peptide", "allele"])


def build_decoy_set(positives: pd.DataFrame, proteome: Dict[str, str],
                    study: str = "skcm_tcga_pan_can_atlas_2018",
                    n_samples: int = 12, ratio: int = 5, seed: int = 0,
                    exclude_samples: Sequence[str] = ()) -> pd.DataFrame:
    """Real TCGA melanoma missense mutations -> mutant/WT peptide pairs,
    matched to the positives on (allele, length) only.

    Use `build_decoy_pool` + `match_decoys_by_binding` for the harder, more
    informative binding-matched version.
    """
    from . import peptides as P
    from . import variants as V

    rng = random.Random(seed)
    sample_ids = [s for s in fetch.cbio_samples(study) if s not in set(exclude_samples)]
    rng.shuffle(sample_ids)
    frames = []
    for sid in sample_ids[:n_samples]:
        try:
            frames.append(V.from_cbioportal(fetch.cbio_mutations(study, sid), sid))
        except Exception:                   # noqa: BLE001 - skip unreachable samples
            continue
    if not frames:
        return pd.DataFrame()
    var = pd.concat(frames, ignore_index=True)
    var = var[var["variant_class"] == "Missense_Mutation"]
    var = var[var["aa_pos"].notna()]
    pep, _ = P.generate_peptides(var, proteome,
                                 lengths=tuple(sorted(set(positives["length"]))),
                                 class2_lengths=())
    pep = pep[pep["wt_peptide"].notna()]
    pool = pep.drop_duplicates("mut_peptide")

    need = positives.groupby(["allele", "length"]).size().to_dict()
    rows = []
    for (allele, L), n in need.items():
        cand = pool[pool["length"] == L]
        if cand.empty:
            continue
        # vary the draw per allele, otherwise every allele gets the identical
        # peptides and the decoy set is far less diverse than its size suggests
        gseed = (seed + abs(hash((allele, int(L)))) % 100000) % (2 ** 31)
        take = cand.sample(n=min(len(cand), n * ratio), random_state=gseed)
        for _, r in take.iterrows():
            rows.append({"peptide": r["mut_peptide"], "wt_peptide": r["wt_peptide"],
                         "allele": allele, "length": int(L), "antigen": r["gene"],
                         "disease": "TCGA-SKCM (unlabelled)", "pubmed_id": None,
                         "label": 0})
    return pd.DataFrame(rows).drop_duplicates(subset=["peptide", "allele"])


def build_decoy_pool(positives: pd.DataFrame, proteome: Dict[str, str],
                     study: str = "skcm_tcga_pan_can_atlas_2018",
                     n_samples: int = 12, pool_ratio: int = 40, seed: int = 0,
                     exclude_samples: Sequence[str] = ()) -> pd.DataFrame:
    """A large unfiltered decoy pool to draw binding-matched decoys from."""
    return build_decoy_set(positives, proteome, study=study, n_samples=n_samples,
                           ratio=pool_ratio, seed=seed,
                           exclude_samples=exclude_samples)


def score_benchmark(bench: pd.DataFrame, iedb_reference: Sequence[str],
                    weights: Dict[str, float], batch_size: int = 500,
                    verbose: bool = True) -> pd.DataFrame:
    """Predict, featurize and score every benchmark row with the SAME code the
    pipeline uses. Only peptide-intrinsic features are used -- expression and
    clonality do not exist for an IEDB epitope, and faking them would be the
    easiest way to manufacture a good-looking AUC."""
    d = bench.copy()
    if "mut_rank" not in d.columns or d["mut_rank"].isna().all():
        d = add_ranks(d, batch_size=batch_size, verbose=verbose)

    d["feat_presentation"] = d["mut_rank"].map(F.f_presentation)
    d["feat_agretopicity"] = [F.f_agretopicity(m, w) for m, w in zip(d["mut_rank"], d["wt_rank"])]
    d["feat_dissimilarity"] = [F.f_dissimilarity(p, w) for p, w in zip(d["peptide"], d["wt_peptide"])]
    d["feat_hydrophobicity"] = d["peptide"].map(F.f_hydrophobicity)
    d["feat_tcr_prior"] = 0.0
    for L, grp in d.groupby("length"):
        ref = [r for r in iedb_reference if len(r) == L]
        q = set(grp["peptide"])
        ref = [r for r in ref if r not in q]     # drop self-matches (leakage control)
        d.loc[grp.index, "feat_tcr_prior"] = F.tcr_prior_scores(list(grp["peptide"]), ref)
    d["feat_expression"] = 0.0
    d["feat_clonality"] = 0.0
    d["feat_mhc2_support"] = 0.0

    intrinsic = {k: v for k, v in weights.items()
                 if k in ("presentation", "agretopicity", "dissimilarity",
                          "tcr_prior", "hydrophobicity")}
    tot = sum(intrinsic.values()) or 1.0
    intrinsic = {k: v / tot for k, v in intrinsic.items()}
    d["score_composite"] = sum(w * d["feat_" + k].fillna(0)
                               for k, w in intrinsic.items())
    no_tcr = {k: v for k, v in intrinsic.items() if k != "tcr_prior"}
    tot2 = sum(no_tcr.values()) or 1.0
    d["score_composite_no_tcr"] = sum((w / tot2) * d["feat_" + k].fillna(0)
                                      for k, w in no_tcr.items())
    d["score_netmhcpan_only"] = d["feat_presentation"]
    return d


def auc(y: Sequence[int], s: Sequence[float]) -> float:
    """Rank-based AUC (Mann-Whitney U), ties handled by average rank."""
    y = np.asarray(y)
    s = np.asarray(s, dtype=float)
    ok = ~np.isnan(s)
    y, s = y[ok], s[ok]
    n1, n0 = int((y == 1).sum()), int((y == 0).sum())
    if n1 == 0 or n0 == 0:
        return float("nan")
    order = np.argsort(s)
    ranks = np.empty(len(s), dtype=float)
    ranks[order] = np.arange(1, len(s) + 1)
    # average ranks for ties
    sv = s[order]
    i = 0
    while i < len(sv):
        j = i
        while j + 1 < len(sv) and sv[j + 1] == sv[i]:
            j += 1
        if j > i:
            ranks[order[i:j + 1]] = (i + j + 2) / 2.0
        i = j + 1
    return float((ranks[y == 1].sum() - n1 * (n1 + 1) / 2.0) / (n1 * n0))


def topk_enrichment(d: pd.DataFrame, score_col: str, k: int = 34) -> Dict[str, float]:
    """How many true positives land in a 34-slot payload drawn from this pool."""
    top = d.sort_values(score_col, ascending=False).head(k)
    base = d["label"].mean()
    hit = top["label"].mean()
    return {"top_k": k, "precision_at_k": float(hit), "baseline_rate": float(base),
            "fold_enrichment": float(hit / base) if base else float("nan")}


def evaluate(d: pd.DataFrame, k: int = 34) -> pd.DataFrame:
    rows = []
    score_cols = ["score_netmhcpan_only", "score_composite_no_tcr", "score_composite"] + \
                 [c for c in d.columns if c.startswith("feat_") and d[c].nunique() > 1]
    for c in score_cols:
        e = topk_enrichment(d, c, k)
        rows.append({"score": c, "AUC_lower_bound": round(auc(d["label"], d[c]), 3),
                     f"precision@{k}": round(e["precision_at_k"], 3),
                     "baseline_positive_rate": round(e["baseline_rate"], 3),
                     "fold_enrichment": round(e["fold_enrichment"], 2)})
    return pd.DataFrame(rows).sort_values("AUC_lower_bound", ascending=False).reset_index(drop=True)
