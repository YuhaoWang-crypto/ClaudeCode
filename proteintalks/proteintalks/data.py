"""Data layer for the ProteinTalks reproduction.

Two backends
------------
``load_real(...)``
    Loads the published ProteinTalks dataset (PTDS) if a processed protein
    matrix and efficacy label table are present on disk.  See
    ``docs/DATA.md`` for what is and is not publicly retrievable.

``SyntheticPerturbationProteome``
    A *mechanistic* simulator of perturbation proteomics.  This exists because
    the published pretraining corpus (16,311 DIA-MS runs) is not redistributable
    here.  It is NOT a stand-in for the paper's biology and reproduces none of
    the paper's biological claims.  Its job is narrower and precise:

      * give the pipeline a ground truth generated by a *real* ODE system, so
        that "does the neural-ODE inductive bias help?" is a well-posed question
        with a known answer;
      * generate the exact tensor shapes and the exact evaluation protocol
        (settings 1/2/3) of the paper, so the code path is the same one that
        would run on the real matrix;
      * let the trivial baselines (drug-mean, cell-line-mean) be measured on a
        dataset with a known, controllable amount of drug-identity signal.

Generative model
----------------
Proteome dynamics for cell line l under drug d:

    dP/dt = -alpha * (P - P0_l)  +  beta * W @ tanh(P - P0_l)  -  gamma * u_d(P)

where ``W`` is a sparse signed protein-interaction matrix shared across cell
lines (the "protein network"), ``P0_l`` is the cell-line baseline proteome, and
``u_d`` is drug inhibition applied to the drug's target proteins.  Efficacy is a
thresholded function of the activity of an essential module at 48 h, so the
label genuinely depends on the *trajectory*, not only on the baseline.

Drug featurisation mirrors the paper: 881 binary fingerprint bits + 54
continuous physicochemical descriptors = 935 features.  Fingerprints are
generated from a latent mechanism-of-action (MOA) class, so that drugs sharing
an MOA have similar fingerprints.  This is what makes leave-one-drug-out
generalisation possible at all, and it is exactly the property the paper's
Figure S5 analysis probes.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field

import numpy as np
import pandas as pd

__all__ = [
    "PerturbationDataset",
    "SyntheticPerturbationProteome",
    "load_real",
    "make_splits",
]


# --------------------------------------------------------------------------- #
# Container
# --------------------------------------------------------------------------- #
@dataclass
class PerturbationDataset:
    """One row per (cell line, drug) condition."""

    p0: np.ndarray            # (n, n_proteins)   baseline proteome
    p_future: np.ndarray      # (n, 3, n_proteins) proteome at 6/24/48 h
    pert: np.ndarray          # (n, n_proteins)   perturbation channel D
    drug_feats: np.ndarray    # (n, 2, 935)       [D1, D2] drug descriptors
    label: np.ndarray         # (n,)              efficacy / synergy, {0,1}
    cell_line: np.ndarray     # (n,)              cell-line index
    drug: np.ndarray          # (n,)              drug index
    protein_names: list[str] = field(default_factory=list)
    cell_line_names: list[str] = field(default_factory=list)
    drug_names: list[str] = field(default_factory=list)
    moa: np.ndarray | None = None   # (n,) latent MOA class, for stratification

    def __len__(self) -> int:
        return self.p0.shape[0]

    @property
    def n_proteins(self) -> int:
        return self.p0.shape[1]

    def subset(self, idx) -> "PerturbationDataset":
        idx = np.asarray(idx)
        return PerturbationDataset(
            p0=self.p0[idx],
            p_future=self.p_future[idx],
            pert=self.pert[idx],
            drug_feats=self.drug_feats[idx],
            label=self.label[idx],
            cell_line=self.cell_line[idx],
            drug=self.drug[idx],
            protein_names=self.protein_names,
            cell_line_names=self.cell_line_names,
            drug_names=self.drug_names,
            moa=None if self.moa is None else self.moa[idx],
        )

    def summary(self) -> str:
        return (
            f"{len(self)} conditions | {self.n_proteins} proteins | "
            f"{len(set(self.cell_line.tolist()))} cell lines | "
            f"{len(set(self.drug.tolist()))} drugs | "
            f"positive rate {self.label.mean():.3f}"
        )


# --------------------------------------------------------------------------- #
# Simulator
# --------------------------------------------------------------------------- #
class SyntheticPerturbationProteome:
    """Mechanistic generator of perturbation proteomics with a known ODE."""

    def __init__(
        self,
        n_proteins: int = 1200,
        n_cell_lines: int = 18,
        n_drugs: int = 63,
        n_moa: int = 20,
        n_targets_per_drug: int = 8,
        edge_density: float = 0.004,
        alpha: float = 0.6,
        beta: float = 0.9,
        gamma: float = 1.6,
        cellline_scale: float = 0.10,
        noise_sd: float = 0.03,
        missing_rate: float = 0.0,
        cl_resistance_sd: float = 0.01,
        positive_rate: float = 0.334,
        timepoints=(0.0, 6.0, 24.0, 48.0),
        seed: int = 0,
    ):
        self.rng = np.random.default_rng(seed)
        self.cl_resistance_sd = cl_resistance_sd
        self.positive_rate = positive_rate
        self.cellline_scale = cellline_scale
        self.n_proteins = n_proteins
        self.n_cell_lines = n_cell_lines
        self.n_drugs = n_drugs
        self.n_moa = n_moa
        self.n_targets_per_drug = n_targets_per_drug
        self.alpha, self.beta, self.gamma = alpha, beta, gamma
        self.noise_sd = noise_sd
        self.missing_rate = missing_rate
        self.timepoints = np.asarray(timepoints, dtype=float)

        self._build_network(edge_density)
        self._build_cell_lines()
        self._build_drugs()

    # -- structure ---------------------------------------------------------- #
    def _build_network(self, density: float) -> None:
        """Sparse signed protein-interaction matrix with a scale-free degree."""
        n = self.n_proteins
        # Preferential-attachment style out-degree so a few hubs dominate.
        hub_score = self.rng.pareto(1.5, size=n) + 1.0
        p_out = hub_score / hub_score.sum()
        n_edges = int(density * n * n)
        src = self.rng.choice(n, size=n_edges, p=p_out)
        dst = self.rng.integers(0, n, size=n_edges)
        w = self.rng.normal(0.0, 1.0, size=n_edges)
        W = np.zeros((n, n), dtype=np.float32)
        np.add.at(W, (dst, src), w)
        np.fill_diagonal(W, 0.0)
        # Spectral normalisation keeps the linearised system stable.
        spec = np.abs(np.linalg.eigvals(W)).max() if n <= 2000 else np.linalg.norm(W, 2)
        self.W = (W / (spec + 1e-8)).astype(np.float32)

        # An "essential module": the proteins whose 48 h activity sets viability.
        # Drawn from the strongest network hubs, so that drug-induced changes
        # propagate into it. In the real label matrix drug identity carries
        # almost all of the efficacy signal (drug-mean AUROC 0.909) and cell-line
        # identity almost none (0.463); the simulator has to reproduce that
        # asymmetry or every downstream comparison on it is meaningless.
        in_deg = np.abs(self.W).sum(axis=0)
        self.essential = np.argsort(in_deg)[-max(20, n // 40):]
        self.essential_w = self.rng.normal(0, 1, size=len(self.essential)).astype(
            np.float32
        )

    def _build_cell_lines(self) -> None:
        n, L = self.n_proteins, self.n_cell_lines
        # Shared mean proteome + low-rank cell-line-specific deviation, which is
        # what real cell-line proteomes look like (a few dominant subtype axes).
        base = self.rng.normal(0.0, 1.0, size=n).astype(np.float32)
        rank = 5
        loadings = self.rng.normal(0, 1, size=(L, rank)).astype(np.float32)
        factors = self.rng.normal(0, 1, size=(rank, n)).astype(np.float32)
        self.P0 = base[None, :] + self.cellline_scale * loadings @ factors
        # Per-cell-line intrinsic resistance shifts the efficacy threshold.
        # The scale is calibrated against the real label matrix (Table S1,
        # C_Efficacy): there, drug identity is highly predictive of efficacy
        # (drug-mean AUROC 0.92) while cell-line identity is not (0.46). A large
        # cell-line offset would invert that and make the benchmark meaningless.
        self.cl_resistance = self.rng.normal(
            0.0, self.cl_resistance_sd, size=L
        ).astype(np.float32)
        self.cell_line_names = [f"CL{i:02d}" for i in range(L)]

    def _build_drugs(self) -> None:
        n, K = self.n_proteins, self.n_drugs
        # Each drug belongs to an MOA class; MOA determines target preference
        # and fingerprint prototype, so fingerprint similarity ~ MOA similarity.
        self.drug_moa = self.rng.integers(0, self.n_moa, size=K)
        moa_target_pool = {
            m: self.rng.choice(n, size=self.n_targets_per_drug * 3, replace=False)
            for m in range(self.n_moa)
        }
        self.drug_targets = [
            self.rng.choice(
                moa_target_pool[self.drug_moa[k]],
                size=self.n_targets_per_drug,
                replace=False,
            )
            for k in range(K)
        ]
        self.drug_potency = self.rng.uniform(0.5, 1.6, size=K).astype(np.float32)

        # 881 binary fingerprint bits + 54 continuous descriptors = 935.
        moa_proto = self.rng.random((self.n_moa, 881)) < 0.15
        bits = np.zeros((K, 881), dtype=np.float32)
        for k in range(K):
            proto = moa_proto[self.drug_moa[k]].astype(np.float32)
            flip = self.rng.random(881) < 0.05   # within-MOA chemical diversity
            bits[k] = np.abs(proto - flip.astype(np.float32))
        moa_phys = self.rng.normal(0, 1, size=(self.n_moa, 54))
        phys = (
            moa_phys[self.drug_moa] + 0.4 * self.rng.normal(0, 1, size=(K, 54))
        ).astype(np.float32)
        self.drug_feats = np.concatenate([bits, phys], axis=1)  # (K, 935)
        self.drug_names = [f"drug{k:02d}_moa{self.drug_moa[k]:02d}" for k in range(K)]

    # -- dynamics ----------------------------------------------------------- #
    def _rhs(self, P: np.ndarray, p0: np.ndarray, inhib: np.ndarray) -> np.ndarray:
        dev = P - p0
        return (
            -self.alpha * dev
            + self.beta * (self.W @ np.tanh(dev))
            - self.gamma * inhib * np.maximum(P, 0.0)
        )

    def _simulate(self, p0, inhib, t_eval, dt: float = 0.25):
        """Fixed-step RK4 integration, sampled at ``t_eval``."""
        P = p0.copy()
        out, t = [], 0.0
        targets = list(t_eval[1:])
        for target in targets:
            n_steps = int(round((target - t) / dt))
            for _ in range(n_steps):
                k1 = self._rhs(P, p0, inhib)
                k2 = self._rhs(P + 0.5 * dt * k1, p0, inhib)
                k3 = self._rhs(P + 0.5 * dt * k2, p0, inhib)
                k4 = self._rhs(P + dt * k3, p0, inhib)
                P = P + (dt / 6.0) * (k1 + 2 * k2 + 2 * k3 + k4)
            t = target
            out.append(P.copy())
        return np.stack(out)

    # -- generation --------------------------------------------------------- #
    def generate(self, conditions=None) -> PerturbationDataset:
        """Generate every (cell line, drug) pair unless ``conditions`` is given."""
        if conditions is None:
            conditions = [
                (l, k) for l in range(self.n_cell_lines) for k in range(self.n_drugs)
            ]

        p0_l, pf_l, pert_l, df_l, cl_l, dr_l, act_l, moa_l = [], [], [], [], [], [], [], []
        # Time is rescaled so the simulated 0-48 h window spans O(10) time units
        # of the intrinsic dynamics; alpha/beta are set relative to this.
        t_eval = self.timepoints / 6.0

        for (l, k) in conditions:
            p0 = self.P0[l].astype(np.float64)
            inhib = np.zeros(self.n_proteins)
            inhib[self.drug_targets[k]] = self.drug_potency[k]
            traj = self._simulate(p0, inhib, t_eval)

            # Viability proxy: weighted activity of the essential module at 48 h.
            act = float(
                self.essential_w @ (traj[-1][self.essential] - p0[self.essential])
            ) / np.sqrt(len(self.essential))

            p0_l.append(p0)
            pf_l.append(traj)
            pert_l.append(inhib)
            df_l.append(np.stack([self.drug_feats[k], self.drug_feats[k]]))
            cl_l.append(l)
            dr_l.append(k)
            act_l.append(act + self.cl_resistance[l])
            moa_l.append(self.drug_moa[k])

        p0 = np.stack(p0_l).astype(np.float32)
        pf = np.stack(pf_l).astype(np.float32)
        pert = np.stack(pert_l).astype(np.float32)
        drug_feats = np.stack(df_l).astype(np.float32)
        act = np.asarray(act_l, dtype=np.float32)

        # Measurement noise, applied after the deterministic simulation.
        p0 = p0 + self.rng.normal(0, self.noise_sd, p0.shape).astype(np.float32)
        pf = pf + self.rng.normal(0, self.noise_sd, pf.shape).astype(np.float32)

        # Binarise efficacy, matching the paper's effective/ineffective
        # dichotomy and its real positive rate (373/1116 = 0.334).
        label = (act < np.quantile(act, self.positive_rate)).astype(np.float32)

        # Min-max normalisation per sample, exactly as the paper's preprocessing
        # ("Prior to inputting the data into the model, we performed min-max
        # normalization on each sample").
        p0, pf = _minmax_per_sample(p0, pf)

        return PerturbationDataset(
            p0=p0,
            p_future=pf,
            pert=pert,
            drug_feats=drug_feats,
            label=label,
            cell_line=np.asarray(cl_l),
            drug=np.asarray(dr_l),
            protein_names=[f"P{i:05d}" for i in range(self.n_proteins)],
            cell_line_names=self.cell_line_names,
            drug_names=self.drug_names,
            moa=np.asarray(moa_l),
        )


def _minmax_per_sample(p0: np.ndarray, pf: np.ndarray):
    """Min-max normalise each condition using the joint range over all times."""
    allv = np.concatenate([p0[:, None, :], pf], axis=1)     # (n, T+1, N)
    lo = allv.min(axis=(1, 2), keepdims=True)
    hi = allv.max(axis=(1, 2), keepdims=True)
    scale = np.maximum(hi - lo, 1e-8)
    allv = (allv - lo) / scale
    return allv[:, 0, :].copy(), allv[:, 1:, :].copy()


# --------------------------------------------------------------------------- #
# Real-data loader
# --------------------------------------------------------------------------- #
def load_real(
    protein_matrix: str,
    label_table: str,
    drug_feature_table: str | None = None,
    timepoints=(0, 6, 24, 48),
) -> PerturbationDataset:
    """Load the published PTDS matrix if it is available locally.

    Expected formats
    ----------------
    protein_matrix
        Long table with columns ``cell_line, drug, time, protein, value`` or a
        wide matrix whose index is ``cell_line|drug|time`` and whose columns are
        protein groups.
    label_table
        Columns ``cell_line, drug, label`` where label is 1 for an effective
        drug and 0 otherwise (paper's CCK8 criteria).
    drug_feature_table
        Columns ``drug`` plus 935 descriptor columns (881 ChemmineR fingerprint
        bits + 54 physicochemical properties).  If absent, one-hot drug identity
        is used and a warning is emitted, since that removes the model's ability
        to generalise to unseen chemistry.
    """
    if not os.path.exists(protein_matrix):
        raise FileNotFoundError(
            f"{protein_matrix} not found. The PTDS protein matrix is not "
            "redistributed with this repository; see docs/DATA.md."
        )
    df = pd.read_csv(protein_matrix)
    required = {"cell_line", "drug", "time", "protein", "value"}
    if not required.issubset(df.columns):
        raise ValueError(f"{protein_matrix} must contain columns {sorted(required)}")

    wide = df.pivot_table(
        index=["cell_line", "drug", "time"], columns="protein", values="value"
    ).sort_index()
    proteins = list(wide.columns)
    # Impute as the paper does: 0.8 x the minimum detected intensity.
    wide = wide.fillna(0.8 * np.nanmin(wide.values))

    labels = pd.read_csv(label_table).set_index(["cell_line", "drug"])["label"]

    if drug_feature_table is not None and os.path.exists(drug_feature_table):
        dfeat = pd.read_csv(drug_feature_table).set_index("drug")
    else:
        dfeat = None

    p0_l, pf_l, pert_l, df_l, lab_l, cl_l, dr_l = [], [], [], [], [], [], []
    cls = sorted({c for c, _, _ in wide.index})
    drugs = sorted({d for _, d, _ in wide.index})
    for cl in cls:
        for dr in drugs:
            try:
                rows = [wide.loc[(cl, dr, t)].values for t in timepoints]
            except KeyError:
                continue
            if (cl, dr) not in labels.index:
                continue
            p0_l.append(rows[0].astype(np.float32))
            pf_l.append(np.stack(rows[1:]).astype(np.float32))
            pert_l.append(np.zeros(len(proteins), dtype=np.float32))
            if dfeat is not None and dr in dfeat.index:
                v = dfeat.loc[dr].values.astype(np.float32)
            else:
                v = np.zeros(935, dtype=np.float32)
                v[drugs.index(dr) % 935] = 1.0
            df_l.append(np.stack([v, v]))
            lab_l.append(float(labels.loc[(cl, dr)]))
            cl_l.append(cls.index(cl))
            dr_l.append(drugs.index(dr))

    if not p0_l:
        raise ValueError("no complete (cell line, drug) time series found")

    p0 = np.stack(p0_l)
    pf = np.stack(pf_l)
    p0, pf = _minmax_per_sample(p0, pf)
    return PerturbationDataset(
        p0=p0,
        p_future=pf,
        pert=np.stack(pert_l),
        drug_feats=np.stack(df_l),
        label=np.asarray(lab_l, dtype=np.float32),
        cell_line=np.asarray(cl_l),
        drug=np.asarray(dr_l),
        protein_names=proteins,
        cell_line_names=cls,
        drug_names=drugs,
    )


# --------------------------------------------------------------------------- #
# Splits: the paper's three evaluation settings
# --------------------------------------------------------------------------- #
def make_splits(
    ds: PerturbationDataset,
    setting: int = 1,
    seed: int = 0,
    holdout=None,
    ratios=(0.7, 0.2, 0.1),
):
    """Return (train_idx, val_idx, test_idx) for the paper's setting 1/2/3.

    setting 1
        Random 0.7 / 0.2 / 0.1 split over conditions (paper: 1070/305/154).
    setting 2
        Leave-one-cell-line-out; ``holdout`` is the cell-line index.
    setting 3
        Leave-one-drug-out; ``holdout`` is the drug index.  The paper describes
        setting 3 as testing unseen drugs.
    """
    rng = np.random.default_rng(seed)
    n = len(ds)
    if setting == 1:
        perm = rng.permutation(n)
        n_tr = int(ratios[0] * n)
        n_va = int(ratios[1] * n)
        return perm[:n_tr], perm[n_tr : n_tr + n_va], perm[n_tr + n_va :]

    if setting == 2:
        key = ds.cell_line
    elif setting == 3:
        key = ds.drug
    else:
        raise ValueError("setting must be 1, 2 or 3")

    if holdout is None:
        raise ValueError("setting 2/3 require `holdout`")
    test = np.where(key == holdout)[0]
    rest = rng.permutation(np.where(key != holdout)[0])
    n_va = max(1, int(0.2 * len(rest)))
    return rest[n_va:], rest[:n_va], test
