"""
R4 — The recorder catalog: taxonomy as data, plus an explicit design rubric.

Every entry is a 5-tuple <Writer, Carrier, Kernel, Reader, Normalizer> as
defined in RECORDER_FRAMEWORK.md, tagged with an evidence level so that
established assays and proposals generated by this framework never blur.

EVIDENCE LEVELS
  cleared    an approved / routinely billed clinical test
  validated  reproduced in independent peer-reviewed cohorts, not a product
  emerging   published human data, single group or small cohorts
  proposed   generated by this framework; no direct human data yet   [HYP]

THE RUBRIC  [HYP -- this is a design heuristic, not a validated predictor]
--------------------------------------------------------------------------
Six gates, each scored 0-1, combined as a WEIGHTED GEOMETRIC MEAN so that a
near-zero on any single gate drags the whole candidate down (a recorder with
no accessible sample is not a biomarker no matter how elegant its chemistry):

  irrev    is the writing chemically irreversible?     -> sets memory
  carrier  is the carrier long-lived and abundant?     -> sets time window
  source   does the readout identify the cell of origin? -> sets specificity
  access   is it in blood / urine / saliva?            -> sets feasibility
  denom    is a shared-parent denominator available?   -> sets robustness
  assay    can it be read with an antibody or lectin
           rather than bespoke MS?                     -> sets cost

The rubric is deliberately transparent and adjustable rather than fitted; its
job is to make the ranking arguable, not to pretend to be predictive.
"""
