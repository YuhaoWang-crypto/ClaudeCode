def score(gates):
    """Weighted geometric mean of the six gates."""
    num = sum(WEIGHTS[k] * np.log(max(v, 1e-6)) for k, v in gates.items())
    den = sum(WEIGHTS.values())
    return float(np.exp(num / den))


def main():
    print("=" * 78)
    print("R4 — Recorder catalog and design rubric")
    print("=" * 78)

    print("\n[1] Recorder classes (R1-R5 from the source framework, R6-R10 added)")
    for cid, (name, desc) in CLASSES.items():
        tag = "" if cid in ("R1", "R2", "R3", "R4", "R5") else "  <- added here"
        print(f"    {cid:<4}{name:<26}{desc}{tag}")

    scored = [(cid, cls, dis, ev, score(g), wr, ca, rd, nm, win)
              for (cid, cls, dis, wr, ca, rd, nm, win, ev, g) in CATALOG]
    scored.sort(key=lambda r: -r[4])

    print(f"\n[2] Catalog ranked by design rubric ({len(CATALOG)} entries)")
    print(f"    {'#':<3}{'candidate':<38}{'cls':<5}{'evidence':<11}{'score':>6}")
    for i, (cid, cls, dis, ev, sc, *_rest) in enumerate(scored, 1):
        print(f"    {i:<3}{cid:<38}{cls:<5}{ev:<11}{sc:>6.2f}")

    print("\n[3] What the ranking says")
    cleared = [r for r in scored if r[3] == "cleared"]
    proposed = [r for r in scored if r[3] == "proposed"]
    print(f"    mean score, cleared assays  : {np.mean([r[4] for r in cleared]):.2f}")
    print(f"    mean score, framework ideas : {np.mean([r[4] for r in proposed]):.2f}")
    print("    The rubric was NOT fitted to the cleared assays, and they still")
    print("    come out on top -- weak evidence that the six gates capture")
    print("    something real about what survives to market. The gap is mostly")
    print("    the `assay` and `denom` gates: most proposals need a bespoke")
    print("    reader (EV capture, flow, MS) and that is where they will die.")

    print("\n[4] Class coverage by evidence level")
    for cid in CLASSES:
        entries = [r for r in CATALOG if r[1] == cid]
        if not entries:
            continue
        evs = {}
        for e in entries:
            evs[e[8]] = evs.get(e[8], 0) + 1
        summary = ", ".join(f"{k}:{v}" for k, v in sorted(evs.items()))
        print(f"    {cid:<5}{CLASSES[cid][0]:<26}{summary}")
    print("    R8 (epigenetic) and R10 (clonal) are the least exploited by the")
    print("    source framework and the most developed elsewhere -- the biggest")
    print("    arbitrage is importing cell-of-origin methylation into the")
    print("    protein-recorder programme, not competing with it.")

    return scored


def export_tsv(path="recorder_catalog.tsv"):
    with open(path, "w") as fh:
        fh.write("id\tclass\tclass_name\tdisease\twriter\tcarrier\treader\t"
                 "normalizer\twindow\tevidence\trubric_score\n")
        for (cid, cls, dis, wr, ca, rd, nm, win, ev, g) in CATALOG:
            fh.write(f"{cid}\t{cls}\t{CLASSES[cls][0]}\t{dis}\t{wr}\t{ca}\t{rd}\t"
                     f"{nm}\t{win}\t{ev}\t{score(g):.3f}\n")
    return path


if __name__ == "__main__":
    main()
